import { readdirSync, copyFileSync, existsSync, mkdirSync, lstatSync } from 'node:fs';
import { resolve, join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateOutputDir, assertNoReparsePoint, WORKSPACE_ROOT, DEFAULT_DIST_DIR } from './path-safety.mjs';

const FORBIDDEN_DIRS = new Set([
  'node_modules',
  'tests',
  'tools',
  'docs',
  '.git',
  '.idea',
  'scratch',
  'artifacts'
]);

const FORBIDDEN_FILES = new Set([
  'package.json',
  'package-lock.json',
  'vite.config.js',
  '.gitignore',
  'README.md',
  'AGENTS.md'
]);

/**
 * Assembles the complete unpacked Chrome Extension into dist/.
 * Preserves panel.html generated by Vite, verification-alert.html,
 * all runtime JS modules verbatim, all CSS files, icons, and classic scripts.
 *
 * Rejects symlink sources and destinations.
 * Forbidden artifact detection throws without deleting unexpected paths.
 */
export async function assembleDist(options = {}) {
  const rootDir = resolve(options.rootDir || WORKSPACE_ROOT);
  const distDir = resolve(options.distDir || DEFAULT_DIST_DIR);

  // Validate output path containment and ensure no reparse points
  validateOutputDir(distDir, rootDir);
  assertNoReparsePoint(distDir);

  if (!existsSync(distDir)) {
    mkdirSync(distDir, { recursive: true });
  }

  const entries = readdirSync(rootDir, { withFileTypes: true });
  const copied = [];

  for (const entry of entries) {
    const name = entry.name;
    const srcPath = join(rootDir, name);

    // Reject symlink sources
    const srcStat = lstatSync(srcPath);
    if (srcStat.isSymbolicLink()) {
      throw new Error(`Security violation: symlink source encountered at: ${srcPath}`);
    }

    // Skip forbidden directories and files
    if (FORBIDDEN_DIRS.has(name) || FORBIDDEN_FILES.has(name)) {
      continue;
    }
    if (name.startsWith('.') || name.endsWith('.log') || name.endsWith('.zip')) {
      continue;
    }

    // Never copy directories from root into dist (Vite handles assets)
    if (entry.isDirectory()) {
      continue;
    }

    // panel.html is compiled and emitted by Vite; never overwrite it with raw source
    if (name === 'panel.html') {
      continue;
    }

    const ext = extname(name).toLowerCase();
    const shouldCopy =
      name === 'manifest.json' ||
      name === 'verification-alert.html' ||
      ext === '.js' ||
      ext === '.css' ||
      ext === '.png' ||
      ext === '.svg' ||
      ext === '.webp';

    if (shouldCopy) {
      const destPath = join(distDir, name);
      assertNoReparsePoint(destPath);
      copyFileSync(srcPath, destPath);
      copied.push(name);
    }
  }

  // Safety assert: verify no forbidden paths exist in dist
  // Requirement: Forbidden artifact detection must ONLY throw, not delete unexpected paths!
  for (const forbidden of [...FORBIDDEN_DIRS, ...FORBIDDEN_FILES]) {
    const checkPath = join(distDir, forbidden);
    if (existsSync(checkPath)) {
      throw new Error(`Security violation: forbidden item "${forbidden}" was found in dist`);
    }
  }

  return { distDir, copiedCount: copied.length, copied };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  assembleDist()
    .then((res) => console.log(`[assemble-dist] Assembled ${res.copiedCount} items into ${res.distDir}`))
    .catch((err) => {
      console.error('[assemble-dist] Error:', err.message);
      process.exit(1);
    });
}
